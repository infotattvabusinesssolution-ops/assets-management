import { randomUUID } from 'node:crypto';
import prisma from '../../config/prisma.js';
import { resolveDbUserId } from '../assets/asset.controller.js';

const scope = req => req.dataScopeFilter || {};
const scheduleInclude = { asset: { include: { site: true, room: true, category: true, custodian: true } } };
const checklist = schedule => {
  try { return JSON.parse(schedule.checklistJson || '[]'); } catch { return []; }
};

export async function getPreventiveDashboard(req, res, next) {
  try {
    const schedules = await prisma.maintenanceSchedule.findMany({
      where: { asset: { is: scope(req) } }, include: scheduleInclude, orderBy: { nextDueDate: 'asc' }
    });
    const runs = await prisma.maintenanceScheduleRun.findMany({ where: { scheduleId: { in: schedules.map(item => item.id) } }, orderBy: { createdAt: 'desc' } });
    const orders = await prisma.maintenanceWorkOrder.findMany({ where: { id: { in: runs.map(run => run.workOrderId) }, asset: { is: scope(req) } }, select: { id: true, workOrderNumber: true, assetId: true, status: true, workType: true, scheduledDate: true, completedDate: true, createdAt: true } });
    const byId = new Map(orders.map(order => [order.id, order]));
    res.json({ success: true,
      schedules: schedules.map(schedule => ({ ...schedule, checklist: checklist(schedule) })),
      generatedWorkOrders: runs.filter(run => byId.has(run.workOrderId)).map(run => ({ ...byId.get(run.workOrderId), scheduleId: run.scheduleId, dueDate: run.dueDate }))
    });
  } catch (error) { next(error); }
}

export async function generateScheduleWorkOrder(scheduleId, reqScope = {}, actor = 'System Scheduler', creatorId = null) {
  const schedule = await prisma.maintenanceSchedule.findFirst({ where: { id: scheduleId, asset: { is: reqScope } }, include: { asset: true } });
  if (!schedule?.active) return { created: 0, skipped: 1, message: 'Schedule is inactive or unavailable.' };
  if (!schedule.asset.active || ['DISPOSED', 'RETIRED'].includes(schedule.asset.lifecycleStatus)) return { created: 0, skipped: 1, message: 'The asset is not eligible for maintenance.' };
  const windowEnd = new Date(Date.now() + schedule.advanceDays * 86400000);
  if (schedule.nextDueDate > windowEnd) return { created: 0, skipped: 1, message: 'The schedule is not due yet.' };
  const run = await prisma.maintenanceScheduleRun.findUnique({ where: { scheduleId_dueDate: { scheduleId, dueDate: schedule.nextDueDate } } });
  if (run) return { created: 0, skipped: 1, message: 'A work order was already generated for this due date.' };
  const open = await prisma.maintenanceWorkOrder.findFirst({ where: { assetId: schedule.assetId, status: { in: ['OPEN', 'ASSIGNED', 'IN_PROGRESS', 'ON_HOLD'] } }, select: { workOrderNumber: true } });
  if (open) return { created: 0, skipped: 1, message: `Asset already has open work order ${open.workOrderNumber}.` };
  const number = `WO-${new Date().getUTCFullYear()}-${randomUUID().slice(0, 8).toUpperCase()}`;
  const user = creatorId ? { id: creatorId } : await prisma.user.findFirst({ where: { active: true, ...(schedule.asset.companyId ? { companyId: schedule.asset.companyId } : {}) }, select: { id: true } });
  if (!user) throw new Error('No active user is available to create the work order.');
  const tasks = checklist(schedule);
  let order;
  try { order = await prisma.$transaction(async tx => {
    const created = await tx.maintenanceWorkOrder.create({ data: {
      workOrderNumber: number, assetId: schedule.assetId, workType: schedule.workType,
      priority: 'MEDIUM', status: 'OPEN', description: [schedule.title, schedule.description].filter(Boolean).join(' — '),
      scheduledDate: schedule.nextDueDate, completionTargetDate: schedule.nextDueDate,
      notes: `Generated by preventive schedule ${schedule.id}`, createdByUserId: user.id,
      checklist: { create: tasks.map(task => ({ task })) },
      statusHistory: { create: { fromStatus: null, toStatus: 'OPEN', changedBy: actor, comments: 'Generated from preventive maintenance schedule' } }
    } });
    await tx.maintenanceScheduleRun.create({ data: { scheduleId, workOrderId: created.id, dueDate: schedule.nextDueDate } });
    await tx.asset.update({ where: { id: schedule.assetId }, data: { lifecycleStatus: 'UNDER_MAINTENANCE' } });
    await tx.assetTransaction.create({ data: { assetId: schedule.assetId, transactionType: 'MAINTENANCE_START', fromStatus: schedule.asset.lifecycleStatus, toStatus: 'UNDER_MAINTENANCE', performedByUserId: user.id, notes: `Work order created: ${number} (preventive schedule)` } });
    return created;
  }); } catch (error) {
    if (error.code === 'P2002') return { created: 0, skipped: 1, message: 'A work order was already generated for this due date.' };
    throw error;
  }
  return { created: 1, skipped: 0, workOrder: order, message: `Created work order ${number} for ${schedule.asset.assetId}.` };
}

export async function generatePreventiveWorkOrders(req, res, next) {
  try {
    const actor = req.user?.fullName || req.user?.username || 'System User';
    const creatorId = await resolveDbUserId(req.user);
    if (req.params.id) {
      const schedule = await prisma.maintenanceSchedule.findFirst({ where: { id: req.params.id, asset: { is: scope(req) } }, select: { id: true } });
      if (!schedule) return res.status(404).json({ success: false, message: 'Schedule not found.' });
      return res.json({ success: true, result: await generateScheduleWorkOrder(schedule.id, scope(req), actor, creatorId) });
    }
    const schedules = await prisma.maintenanceSchedule.findMany({ where: { active: true, asset: { is: scope(req) } }, select: { id: true } });
    const results = [];
    for (const schedule of schedules) {
      try { results.push(await generateScheduleWorkOrder(schedule.id, scope(req), actor, creatorId)); }
      catch (error) { results.push({ created: 0, skipped: 1, message: error.message }); }
    }
    const created = results.reduce((sum, result) => sum + result.created, 0);
    res.json({ success: true, result: { created, skipped: results.length - created, message: `Created ${created} due work order(s).` } });
  } catch (error) { next(error); }
}

export async function runDuePreventiveSchedules() {
  const schedules = await prisma.maintenanceSchedule.findMany({ where: { active: true, autoGenerateWorkOrders: true }, select: { id: true } });
  for (const schedule of schedules) {
    try { await generateScheduleWorkOrder(schedule.id); }
    catch (error) { console.error(`Preventive schedule ${schedule.id} failed:`, error); }
  }
}
